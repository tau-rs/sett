#!/usr/bin/env node
// Generates the agent layer from the built artefacts: llms.txt (repo root) and
// skills/sett/SKILL.md. Inputs are packages/ui/custom-elements.json (the element API),
// packages/storybook/storybook-static/index.json (every story id, one per state) and the
// body of DESIGN.md (the rules). Run by the root `pnpm build`; packages/agent/test checks
// the committed files against a fresh render, so a manifest or story change that is not
// followed by a build fails `pnpm test`.
//
// Output is sorted by tag name: the analyzer's module order churns between builds and
// must not show up in the generated files.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const INPUTS = {
  manifest: join(ROOT, 'packages', 'ui', 'custom-elements.json'),
  index: join(ROOT, 'packages', 'storybook', 'storybook-static', 'index.json'),
  design: join(ROOT, 'DESIGN.md'),
};
export const OUTPUTS = {
  llms: join(ROOT, 'llms.txt'),
  skill: join(ROOT, 'skills', 'sett', 'SKILL.md'),
};
export const STORYBOOK_URL = 'https://tau-rs.github.io/sett';
const BANNER = 'generated by scripts/gen-agent-layer.mjs from packages/ui/custom-elements.json, the Storybook stories index and DESIGN.md. Do not edit; run pnpm build.';

/** Reads the three inputs from disk. Throws with a hint when a build artefact is missing. */
export function readInputs(paths = INPUTS) {
  for (const [name, path] of Object.entries(paths)) {
    if (!existsSync(path)) throw new Error(`gen-agent-layer: missing ${name} at ${path} (run pnpm -r build first)`);
  }
  return {
    manifest: JSON.parse(readFileSync(paths.manifest, 'utf8')),
    index: JSON.parse(readFileSync(paths.index, 'utf8')),
    design: readFileSync(paths.design, 'utf8'),
  };
}

/** Story files are listed relative to packages/storybook (the Storybook config dir's parent). */
const readStorySource = (importPath) => readFileSync(join(ROOT, 'packages', 'storybook', importPath), 'utf8');
const dirOf = (path) => path.replace(/\/[^/]+$/, '').replace(/^.*?(src\/)/, '$1');
const oneLine = (s) => (s ?? '').replace(/\s+/g, ' ').trim();

/**
 * The elements, sorted by tag, each with its stories. The index carries no component
 * field, so a story covers the elements declared in its own directory; an element with no
 * story there (the menu, shown under the selector) takes the stories whose source uses its
 * tag. `storySource` reads a story file by its importPath; the default reads from disk.
 */
export function elements({ manifest, index, storySource = readStorySource }) {
  const stories = Object.values(index.entries).filter((e) => e.type === 'story');
  const byDir = new Map();
  for (const s of stories) {
    const dir = dirOf(s.importPath);
    if (!byDir.has(dir)) byDir.set(dir, []);
    byDir.get(dir).push({ id: s.id, name: s.name, title: s.title });
  }
  const sources = new Map();
  const usedIn = (tag) => stories.filter((s) => {
    if (!sources.has(s.importPath)) sources.set(s.importPath, storySource(s.importPath));
    return new RegExp(`<${tag}(?![\\w-])`).test(sources.get(s.importPath));
  }).map((s) => ({ id: s.id, name: s.name, title: s.title }));
  const out = [];
  for (const mod of manifest.modules) {
    for (const d of mod.declarations ?? []) {
      if (!d.tagName) continue;
      out.push({
        tag: d.tagName,
        className: d.name,
        module: mod.path,
        description: oneLine(d.description),
        attributes: (d.attributes ?? []).map((a) => ({ name: a.name, type: a.type?.text, default: a.default, description: oneLine(a.description) })),
        slots: (d.slots ?? []).map((s) => ({ name: s.name || '(default)', description: oneLine(s.description) })),
        parts: (d.cssParts ?? []).map((p) => ({ name: p.name, description: oneLine(p.description) })),
        events: (d.events ?? []).map((e) => ({ name: e.name, description: oneLine(e.description) })),
        stories: byDir.get(dirOf(mod.path)) ?? usedIn(d.tagName),
      });
    }
  }
  return out.sort((a, b) => a.tag.localeCompare(b.tag));
}

/** Stories whose directory declares no element: the recipe screens. */
export function orphanStories({ manifest, index }) {
  const dirs = new Set(manifest.modules.filter((m) => (m.declarations ?? []).some((d) => d.tagName)).map((m) => dirOf(m.path)));
  return Object.values(index.entries).filter((e) => e.type === 'story' && !dirs.has(dirOf(e.importPath))).map((s) => ({ id: s.id, name: s.name, title: s.title }));
}

export function docsPages({ index }) {
  return Object.values(index.entries).filter((e) => e.type === 'docs').map((d) => ({ id: d.id, title: d.title })).sort((a, b) => a.id.localeCompare(b.id));
}

/** DESIGN.md without its front matter, split into `## ` sections keyed by heading. */
export function designSections(design) {
  const body = design.replace(/^---[\s\S]*?\n---\n/, '');
  const sections = {};
  let key = '';
  for (const line of body.split('\n')) {
    const h = line.match(/^## (.+)$/);
    if (h) { key = h[1].trim(); sections[key] = []; continue; }
    if (key) sections[key].push(line);
  }
  for (const k of Object.keys(sections)) sections[k] = sections[k].join('\n').trim();
  return sections;
}

const attrText = (a) => `${a.name}${a.type ? `=${a.type.replace(/\s+\|\s+undefined$/, '')}` : ''}`;
const storyText = (s) => `${s.id} (${s.name})`;

export function renderLlms(inputs) {
  const els = elements(inputs);
  const lines = [
    '# sett',
    '',
    `> Design system for tau-rs developer tools: Lit web components (prefix \`sett-\`), DTCG tokens (CSS prefix \`--sett-\`), dense, quiet, dark-first, plain DOM. ${BANNER}`,
    '',
    `Storybook: ${STORYBOOK_URL}/ · a story is ${STORYBOOK_URL}/?path=/story/<id> · the stories index is ${STORYBOOK_URL}/index.json · the element manifest is packages/ui/custom-elements.json (custom-elements-manifest 1.0.0) · the rules are DESIGN.md · the agent brief is skills/sett/SKILL.md.`,
    '',
    "Sample data: `import { ripgrep, zero2prod, zed } from '@tau-rs/sett/fixtures'`, three real repositories typed `Fixture`, read with `unitOf`, `unitPorts`, `insideOf`, `linksOf` from `@tau-rs/sett`; a separate entry, so the element bundle does not carry them.",
    '',
    '## Elements',
    '',
    'One line per element: tag · what it is · attrs (name=type) · slots · CSS parts · events · the story ids that show each state, with the state in parentheses.',
    '',
  ];
  for (const e of els) {
    const cols = [
      `- ${e.tag}: ${e.description || e.className}`,
      `attrs: ${e.attributes.length ? e.attributes.map(attrText).join(', ') : 'none'}`,
      `slots: ${e.slots.length ? e.slots.map((s) => s.name).join(', ') : 'none'}`,
      `parts: ${e.parts.length ? e.parts.map((p) => p.name).join(', ') : 'none'}`,
      `events: ${e.events.length ? e.events.map((v) => v.name).join(', ') : 'none'}`,
      `stories: ${e.stories.length ? e.stories.map(storyText).join(', ') : 'none'}`,
    ];
    lines.push(cols.join(' · '));
  }
  const recipes = orphanStories(inputs);
  if (recipes.length) {
    lines.push('', '## Recipes', '', 'Screens composed from the elements above; the reference for how they sit together.', '');
    for (const s of recipes) lines.push(`- ${storyText(s)}`);
  }
  const docs = docsPages(inputs);
  if (docs.length) {
    lines.push('', '## Docs', '');
    for (const d of docs) lines.push(`- ${d.title}: ${STORYBOOK_URL}/?path=/docs/${d.id}`);
  }
  return lines.join('\n') + '\n';
}

export function renderSkill(inputs) {
  const els = elements(inputs);
  const sections = designSections(inputs.design);
  const need = (k) => { if (!sections[k]) throw new Error(`gen-agent-layer: DESIGN.md has no "## ${k}" section`); return sections[k]; };
  const lines = [
    '---',
    'name: sett',
    'description: Use when building or reviewing UI for a tau-rs developer tool (arch first) with the sett design system - Lit web components with the sett- prefix, DTCG tokens with the --sett- CSS prefix, dense, quiet, dark-first, plain DOM.',
    '---',
    '',
    '# sett',
    '',
    `<!-- ${BANNER} -->`,
    '',
    '## What sett is for',
    '',
    need('What sett is for'),
    '',
    need('Principles that constrain visual design'),
    '',
    '## Rules',
    '',
    'DESIGN.md is normative: where a mock, a screenshot, a story or this file disagrees with it, DESIGN.md wins. Its front matter is a resolved summary of the tokens; the values below come from the same source.',
    '',
    '### Colours',
    '',
    need('Colours'),
    '',
    '### Type',
    '',
    need('Type'),
    '',
    '### Spacing, radius, stroke',
    '',
    need('Spacing, radius, stroke'),
    '',
    '### Motion',
    '',
    need('Motion'),
    '',
    '### Rules the components encode',
    '',
    need('Rules the components encode'),
    '',
    '### Glyph vocabulary',
    '',
    need('Glyph vocabulary'),
    '',
    '## Hard constraints',
    '',
    '- Never write a raw hex, px or duration in a component or a consumer stylesheet; reference a token. A grep in CI fails on any hex outside packages/tokens.',
    '- Motion: only `frame.live`, `frame.waiting`, `item-pulse` and the session dot pulse. Anything else that animates is a bug.',
    '- No modal, dialog or toast. If a spec seems to need one, stop and ask.',
    '- Plain DOM: Lit web components, no framework runtime, no icon font, no external CSS. Everything must load inside Eclipse Theia as a script.',
    '- Dark mode is required: every story is checked in both themes and an axe violation (contrast included) fails its test.',
    '- Before using any attribute, property, slot or CSS part, check the element index below or packages/ui/custom-elements.json. Do not invent props.',
    '',
    '## How to reference tokens',
    '',
    'Tokens are normative in `packages/tokens/src/*.json` (DTCG 2025.10) and built to `@tau-rs/sett-tokens`. The name is the DTCG path.',
    '',
    '- CSS: `var(--sett-<path>)`, e.g. `var(--sett-color-sel)`, `var(--sett-session-yk-sub)`, `var(--sett-radius-chip)`, `var(--sett-space-2)`. Load `@tau-rs/sett-tokens/sett.css` once: `:root` is light, `[data-theme="dark"]` and `prefers-color-scheme: dark` are dark.',
    "- TypeScript: `import { light, dark, base, sessionOrder, cssVar } from '@tau-rs/sett-tokens'`; `cssVar('color', 'sel')` returns the `var(...)` string.",
    '- Rust: `sett-tokens` crate, one `pub const` per token (colours as `[f32; 3]`, dimensions as `f32`); map primitives are values, not CSS.',
    '- Session colours: assign in order `yk, tl, mg, cy, ol, sn, pl`; each has `main`, `sub` (outlines, dots, guide lines, never text) and `bg`.',
    '',
    '## How to find a story',
    '',
    `Every element has a story per state, and every story is a test that runs in both themes. Storybook: ${STORYBOOK_URL}/ . A story is \`${STORYBOOK_URL}/?path=/story/<id>\`; the ids are listed per element below and in \`llms.txt\`. The full index is \`${STORYBOOK_URL}/index.json\` (\`packages/storybook/storybook-static/index.json\` after \`pnpm build\`). Locally: \`pnpm --filter @tau-rs/sett-storybook dev\` then open the same path on port 6006. Stories live next to the components in \`packages/ui/src/<family>/*.stories.ts\`.`,
    '',
    '## Elements',
    '',
    'Tag · attributes (name=type) · slots · CSS parts · events, then the stories that show each state.',
    '',
  ];
  const item = (x) => `  - \`${x.name}\`${x.description ? ` — ${x.description}` : ''}`;
  for (const e of els) {
    lines.push(`### \`<${e.tag}>\``, '', e.description || e.className, '');
    if (e.attributes.length) lines.push('- attrs:', ...e.attributes.map((a) => item({ name: attrText(a), description: a.description })));
    if (e.slots.length) lines.push('- slots:', ...e.slots.map(item));
    if (e.parts.length) lines.push('- parts:', ...e.parts.map(item));
    if (e.events.length) lines.push('- events:', ...e.events.map(item));
    lines.push('- stories:', ...(e.stories.length ? e.stories.map((s) => `  - \`${s.id}\` ${s.name}`) : ['  - none']), '');
  }
  const recipes = orphanStories(inputs);
  if (recipes.length) {
    lines.push('## Recipes', '', 'Screens composed from the elements; the reference for how they sit together.', '');
    for (const s of recipes) lines.push(`- \`${s.id}\` ${s.name}`);
    lines.push('');
  }
  const docs = docsPages(inputs);
  if (docs.length) {
    lines.push('## Docs pages', '');
    for (const d of docs) lines.push(`- ${d.title}: ${STORYBOOK_URL}/?path=/docs/${d.id}`);
    lines.push('');
  }
  return lines.join('\n');
}

export function render(inputs) {
  return { llms: renderLlms(inputs), skill: renderSkill(inputs) };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const inputs = readInputs();
  const out = render(inputs);
  mkdirSync(dirname(OUTPUTS.skill), { recursive: true });
  writeFileSync(OUTPUTS.llms, out.llms);
  writeFileSync(OUTPUTS.skill, out.skill);
  console.log(`gen-agent-layer: ${elements(inputs).length} elements → llms.txt, skills/sett/SKILL.md`);
}
